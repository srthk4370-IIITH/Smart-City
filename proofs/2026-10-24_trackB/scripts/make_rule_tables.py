"""Write the per-slice before/after tables for the post-rules (proofs/2026-10-24_trackB/rules_tables.md) and the raw
per-row changes (raw/<set>_<tag>_changes.jsonl). Short stdout summary only."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import eval_rules as E
import trackb_lib as L

OUT = Path(__file__).resolve().parent.parent
KEPT = ["erratic", "limit", "quality_cause", "rel_power", "rel_level", "water_cause", "glitch", "floor250", "chatter", "cause", "fkind"]
TARGET = {"erratic": "erratic", "limit": "rw5_acidic", "quality_cause": "rw5_acidic", "rel_power": "role_power", "rel_level": "role_water",
          "water_cause": "role_water", "glitch": "rw5_glitch", "floor250": "rw5_co2_floor", "chatter": "rw5_chatter",
          "cause": "ALL", "fkind": "sensor_fault"}
REJECTED = ["rel_water", "floor", "floor280", "glitch_v1"]
SHOW = ["ALL", "stage_early", "stage_1.5h", "stage_3h", "compound", "calm_or_routine", "sensor_fault", "seen_unseen",
        "seen_unseen_sepoct", "role_power", "role_water", "role_air_quality", "role_weather", "role_hvac", "role_occupancy",
        "status_power_water", "water_cause", "erratic", "exp_vs_gradual", "rw_old_shift", "power_drop",
        "rw5_glitch", "rw5_chatter", "rw5_chatter_next", "rw5_co2_floor", "rw5_acidic", "rw5_gap_calm", "rw5_gap_event",
        "rw5_gap_recovery", "rw5_holiday", "rw5_daily_cycle", "rw5_hvac_stuck_on", "rw5_hvac_weekend_off"]
KEYS = ("pattern", "status", "cause", "fault_kind", "event_active")


def cell(row, k):
    if k not in row:
        return ""
    n, b, a, w, l = row[k]
    return f"{100*b/n:.1f} → {100*a/n:.1f} ({w}/{l})"


def chatter_pairs(pairs):
    after = {a["id"]: a for _, a in pairs}
    before = {b["id"]: b for b, _ in pairs}
    out = {}
    for tag, src in (("before", before), ("after", after)):
        ok = tot = 0
        for i, s in src.items():
            if i.endswith("-next") or "rw5_chatter" not in s["slices"]:
                continue
            j = i + "-next"
            if j in src:
                tot += 1
                ps, pj = (s.get("pred") or {}).get("status"), (src[j].get("pred") or {}).get("status")
                ok += ps == pj == "warning"
        out[tag] = (ok, tot)
    return out


def main():
    md = ["# Post-rule tables (generated by scripts/make_rule_tables.py)", "",
          "Cells: v2 → v2+rules accuracy % (paired wins/losses). Scorer = training/v2/post/common_v2.score_one "
          "(the host_eval3e scorer). Stored v2 outputs = tag v2cuda.", ""]
    (OUT / "raw").mkdir(exist_ok=True)
    manifest = {}
    for ds in ("test", "rw5test", "dev", "rw5dev"):
        pairs, ch = L.run_rules(ds, KEPT)
        tab = L.slice_table(pairs)
        fn = OUT / "raw" / f"{ds}_v2cuda_kept_changes.jsonl"
        with open(fn, "w") as f:
            for c in ch:
                f.write(json.dumps(c, default=str) + "\n")
        manifest[fn.name] = hashlib.md5(fn.read_bytes()).hexdigest()
        md += [f"## {ds}: v2 → v2 + kept rules ({len(pairs)} rows, {len(ch)} rows changed)", "",
               "| slice | n | " + " | ".join(KEYS) + " |", "|---|---|" + "---|" * len(KEYS)]
        for s in SHOW:
            if s in tab:
                md.append(f"| {s} | {tab[s]['n']} | " + " | ".join(cell(tab[s], k) for k in KEYS) + " |")
        gains, drops = E.summarise(tab)
        md += ["", f"Largest drop over all slices (n ≥ {E.MIN_N}): " + (E.fmt(drops[0]) if drops else "none"), ""]
        if ds.startswith("rw5"):
            cp = chatter_pairs(pairs)
            md += [f"Chatter pair consistency (both windows warning): before {cp['before'][0]}/{cp['before'][1]}, "
                   f"after {cp['after'][0]}/{cp['after'][1]}", ""]
        print(ds, "ALL status", cell(tab["ALL"], "status"), "| worst", E.fmt(drops[0]) if drops else "none")
    # per-rule gate
    md += ["## Each rule alone (gate: target slice up, no slice with n ≥ 10 down > 1 pt)", "",
           "| rule | set | rows changed | ALL status W/L | ALL cause W/L | target slice | target status | worst slice drop |",
           "|---|---|---|---|---|---|---|---|"]
    for r in KEPT + REJECTED:
        for ds in ("dev", "rw5dev", "test", "rw5test"):
            pairs, ch = L.run_rules(ds, [r])
            tab = L.slice_table(pairs)
            gains, drops = E.summarise(tab)
            t = TARGET.get(r, "ALL")
            ts = cell(tab[t], "status") if t in tab else "n/a"
            a = tab["ALL"]
            md.append(f"| {r} | {ds} | {len(ch)} | {a['status'][3]}/{a['status'][4]} | {a['cause'][3]}/{a['cause'][4]} | {t} | {ts} | "
                      f"{E.fmt(drops[0]) if drops else 'none'} |")
    # the same rules on the best 3f candidate (robustness: rules are not tuned to v2's own errors)
    md += ["", "## Same kept rules on mixA50 (best 3f candidate, stored outputs)", "",
           "| set | slice | n | pattern | status | cause |", "|---|---|---|---|---|---|"]
    for ds in ("test", "rw5test"):
        pairs, ch = L.run_rules(ds, KEPT, "mixA50")
        tab = L.slice_table(pairs)
        for s in ("ALL", "stage_early", "stage_1.5h", "stage_3h", "compound", "calm_or_routine", "role_power", "seen_unseen"):
            if s in tab:
                md.append(f"| {ds} | {s} | {tab[s]['n']} | {cell(tab[s], 'pattern')} | {cell(tab[s], 'status')} | {cell(tab[s], 'cause')} |")
    (OUT / "rules_tables.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (OUT / "raw" / "manifest_rules.json").write_text(json.dumps(manifest, indent=1))
    print("wrote rules_tables.md")


if __name__ == "__main__":
    main()
