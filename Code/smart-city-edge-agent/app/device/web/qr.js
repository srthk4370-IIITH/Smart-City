/* "Share as QR" on the incident sheet. GET /api/incidents/{id}/qr returns 1-3 signed QR codes (SVG) holding the
   whole report; any phone camera opens the static viewer (print / save as PDF there). Nothing is stored online.
   Uses SCE_H from app.js; adds one button to the incident sheet header and a full-screen overlay. */
(function () {
  'use strict';
  const { api, toast } = window.SCE_H || {};
  if (!api) return;
  const css = '#qr-ov{position:fixed;inset:0;z-index:99;background:#fff;color:#111;display:flex;flex-direction:column;align-items:center;padding:14px 16px 18px;overflow:auto;font:15px/1.4 -apple-system,system-ui,sans-serif}' +
    '#qr-ov[hidden]{display:none}#qr-ov h2{margin:4px 0 2px;font-size:20px;text-align:center}#qr-ov .qr-sub{margin:0 0 8px;color:#555;text-align:center;max-width:36em}' +
    '#qr-ov .qr-img{width:min(88vw,70vh,560px);aspect-ratio:1;border:1px solid #ddd;border-radius:8px;overflow:hidden;background:#fff}#qr-ov .qr-img svg{width:100%;height:100%;display:block}' +
    '#qr-ov .qr-row{display:flex;gap:10px;margin:10px 0;flex-wrap:wrap;justify-content:center}#qr-ov button{min-height:44px;padding:0 18px;border-radius:10px;border:1px solid #bbb;background:#f2f2f7;color:#111;font:inherit;cursor:pointer}' +
    '#qr-ov button.pri{background:#0a63d6;border-color:#0a63d6;color:#fff}#qr-ov details{max-width:36em;width:100%;color:#444;font-size:13px}#qr-ov code{word-break:break-all}' +
    '.qr-share{margin-right:6px;font-size:13px;width:auto!important;border-radius:22px!important;padding:0 14px}';
  const st = document.createElement('style'); st.textContent = css; document.head.appendChild(st);
  const ov = document.createElement('div'); ov.id = 'qr-ov'; ov.hidden = true; ov.setAttribute('role', 'dialog'); ov.setAttribute('aria-modal', 'true'); ov.setAttribute('aria-label', 'Share incident as QR code');
  document.body.appendChild(ov);
  const el = (t, a, ...k) => { const e = document.createElement(t); for (const x in a || {}) { if (x === 'text') e.textContent = a[x]; else if (x.startsWith('on')) e[x] = a[x]; else e.setAttribute(x, a[x]); } k.forEach((c) => c && e.append(c)); return e; };
  const S = { d: null, i: 0, id: '' };
  function close() { ov.hidden = true; ov.replaceChildren(); document.removeEventListener('keydown', onKey); }
  function onKey(e) { if (e.key === 'Escape') close(); }
  function draw() {
    const d = S.d, n = d.chunks;
    const img = el('div', { class: 'qr-img', role: 'img', 'aria-label': 'QR code ' + (S.i + 1) + ' of ' + n });
    img.innerHTML = d.svgs[S.i]; // SVG generated by this board
    ov.replaceChildren(
      el('h2', { text: n > 1 ? 'Scan code ' + (S.i + 1) + ' of ' + n : 'Scan to open the report' }),
      el('p', { class: 'qr-sub', text: S.id + ': scan with any phone camera' + (n > 1 ? '. Scan all ' + n + ' codes, one after the other; the report opens when the last one is read.' : '.') + ' The report is inside the code; nothing is stored online.' }),
      img,
      el('div', { class: 'qr-row' },
        n > 1 ? el('button', { type: 'button', text: 'Previous', disabled: S.i ? null : 'true', onclick: () => { if (S.i) { S.i--; draw(); } } }) : null,
        n > 1 && S.i < n - 1 ? el('button', { type: 'button', class: 'pri', text: 'Next code', onclick: () => { S.i++; draw(); } }) : null,
        el('button', { type: 'button', class: n > 1 && S.i < n - 1 ? '' : 'pri', text: 'Done', onclick: close })),
      el('details', {}, el('summary', { text: 'Technical details' }),
        el('p', {}, 'Signed by board ', el('b', { text: d.board }), '. Public key (add it to the viewer trust list): ', el('code', { text: d.pubkey })),
        el('p', {}, d.payload_chars + ' characters, ' + n + ' code' + (n > 1 ? 's' : '') + ', QR version ' + d.versions.join(', ') + '. Viewer: ', el('code', { text: d.viewer }))));
    const b = ov.querySelector('button.pri'); if (b) b.focus();
  }
  async function open(id) {
    try { S.d = await api('/api/incidents/' + encodeURIComponent(id) + '/qr'); } catch (e) { toast('QR report: ' + (e.message || e), true); return; }
    S.i = 0; S.id = id; ov.hidden = false; document.addEventListener('keydown', onKey); draw();
  }
  function mount() {
    const row = document.querySelector('#isheet .sheet-row'); if (!row || row.querySelector('.qr-share')) return;
    const b = el('button', { type: 'button', class: 'ibtn qr-share', text: 'Share as QR', title: 'Show this incident as QR code(s) that any phone can open', onclick: () => { const t = document.getElementById('isheet-t'); const m = t && t.textContent.match(/INC-\d+/); if (m) open(m[0]); else toast('QR report: no incident id on this sheet', true); } });
    const x = row.querySelector('.x'); row.insertBefore(b, x || null);
  }
  mount();
})();
