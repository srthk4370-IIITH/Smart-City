def fill(key, vals, rng, avoid=()):
    """Pick one template for key and fill it from evidence strings. `avoid`: placeholders whose evidence
    contradicts the label here (e.g. halves that do not rise yet for a 30-min-old rise); templates using them
    are skipped (fallback: all templates, but every key has avoid-free variants)."""
    opts = [t for t in T[key] if not any(a in t for a in avoid)] or T[key]
    return rng.choice(opts).format(**vals)
