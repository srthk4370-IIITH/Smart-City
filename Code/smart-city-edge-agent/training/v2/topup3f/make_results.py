"""Writes proofs/2026-10-23_v2t3f/RESULTS_TABLES.md + copies raw eval samples (all sets, all candidates) to
proofs/.../raw/. Prints one line.   python make_results.py"""
import json, shutil, subprocess, sys
from pathlib import Path
R = Path.home() / "smartcity_runs" / "agents_v2_topup3f"
P = Path("/mnt/c/Users/hp/Desktop/qidk/proofs/2026-10-23_v2t3f")
H = Path(__file__).resolve().parent.parent / "topup3e"
KEY = ["ALL", "stage_early", "stage_1.5h", "stage_3h", "compound", "calm_or_routine", "routine", "role_power", "role_water",
       "sensor_fault", "seen_seen", "seen_unseen", "set_realworld", "set_weak", "set_host400", "set_testrest"]
out = ["# 3f per-candidate tables (generated by topup3f/make_results.py)", "",
       "Cells: v2 -> candidate % (paired wins/losses vs v2). Host Q4_0 greedy, CUDA b11815, same scoring as 3e.", ""]
for st in ("dev", "rw5dev", "test", "rw5test"):
    E = R / f"eval_{st}"
    if not (E / "eval" / "v2cuda" / "samples.jsonl").exists():
        continue
    n = sum(1 for _ in open(E / "eval3e.jsonl"))
    cands = [d.name for d in sorted((E / "eval").iterdir()) if d.name != "v2cuda" and (d / "samples.jsonl").exists()
             and sum(1 for _ in open(d / "samples.jsonl")) >= n]
    if not cands:
        continue
    subprocess.run([sys.executable, str(H / "host_eval3e.py"), "table", "--out", str(E), "--ref", "v2cuda", "--cand", *cands], cwd=H, capture_output=True)
    T = json.loads((E / "tables.json").read_text())
    rows = KEY + sorted(s for s in T[cands[0]] if s.startswith("rw5_"))
    out += [f"## {st} (n={n})", "", "| slice | n | " + " | ".join(f"{c} pattern | {c} status" for c in cands) + " |",
            "|---|---|" + "---|---|" * len(cands)]
    f = lambda x: f"{100*x['ref']/x['n']:.1f}→{100*x['cand']/x['n']:.1f} ({x['wins']}/{x['losses']})"
    for s in rows:
        if s not in T[cands[0]]:
            continue
        cells = [f(T[c][s][k]) if s in T[c] and k in T[c][s] else "" for c in cands for k in ("pattern", "status")]
        out.append(f"| {s} | {T[cands[0]][s]['n']} | " + " | ".join(cells) + " |")
    js = {c: f"{T[c]['ALL']['json']['cand']}/{T[c]['ALL']['json']['n']}" for c in cands}
    out += ["", f"JSON valid: {js}", ""]
    for d in (E / "eval").iterdir():
        dst = P / "raw" / st / d.name
        dst.mkdir(parents=True, exist_ok=True)
        for fn in ("samples.jsonl", "run.json"):
            if (d / fn).exists():
                shutil.copy(d / fn, dst / fn)
(P / "RESULTS_TABLES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("RESULTS_TABLES.md:", len(out), "lines")
