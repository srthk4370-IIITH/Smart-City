"""Turn the device's incident log into training data, so the models can improve from real use.

Why this exists
---------------
The owner wants the system to be self-learning. Every LLM call the app makes is already persisted
in state/incidents.jsonl with everything needed for that:

  prompt      the exact prompt the model saw
  raw         the model's own output, BEFORE any policy repair
  parsed      the output after policy validation and repair
  valid       whether it passed the policy gate
  repairs     what policy had to fix, and how
  errors      what policy rejected
and per incident the operator's verdict (approval: approved | dismissed) and note.

This script reads that log and writes three datasets:

  sft_positive.jsonl   operator-APPROVED calls that passed policy with NO repairs. The model got it
                       right and a human agreed: (prompt, completion) for supervised fine-tuning.
  dpo_pairs.jsonl      calls policy had to REPAIR. The repaired output is "chosen", the model's raw
                       output is "rejected". These pairs need no human labelling at all - policy
                       already knows the correct form - so they accumulate from day one.
  dismissed.jsonl      operator-DISMISSED incidents with the operator's note. Not used directly for
                       training: a dismissal says the answer was unhelpful, not what the right answer
                       was. Kept for review and to build better pairs later.

The incident log is append-only: a record is re-written on every state change (approval included),
so the LAST line for each incident id is the authoritative one.

  python export_feedback.py                       # pull from the QIDK over adb and export
  python export_feedback.py --log incidents.jsonl # export from a local copy
"""
from __future__ import annotations

import argparse
import json
import subprocess
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ADB = str(HERE.parents[2] / "platform-tools" / "adb.exe")
DEVICE_LOG = "/data/local/tmp/smart_city_edge/state/incidents.jsonl"
DEVICE_ARCHIVE = "/data/local/tmp/smart_city_edge/state/incidents.archive.jsonl"
AGENT_PREFILL = '{"pattern": "'
FIELD_ORDER = ("pattern", "status", "observations", "likely_cause", "confidence", "action")
POLICY_ONLY_FIELDS = {"requires_human_approval"}  # set by policy, never generated by the model


def pull_log() -> list[str]:
    # archive first (older incidents moved out by the store's retention), then the live store, so
    # the newest record for an id still wins in latest_per_incident
    lines: list[str] = []
    for path in (DEVICE_ARCHIVE, DEVICE_LOG):
        r = subprocess.run([ADB, "exec-out", "cat", path], capture_output=True, timeout=120)
        out = r.stdout.decode("utf-8", errors="replace")
        if r.returncode != 0 or "No such file" in out[:200]:
            if path == DEVICE_LOG:
                raise SystemExit(f"could not read {DEVICE_LOG} over adb: {r.stderr.decode(errors='replace')[:200]}")
            continue
        lines += out.splitlines()
    return lines


def latest_per_incident(lines: list[str]) -> list[dict]:
    """The log is append-only; keep the newest record for each incident id."""
    latest: dict[str, dict] = {}
    for ln in lines:
        ln = ln.strip()
        if not ln:
            continue
        try:
            inc = json.loads(ln)
        except json.JSONDecodeError:
            continue  # a torn final line from a power cut must not stop the export
        if inc.get("id"):
            latest[inc["id"]] = inc
    return list(latest.values())


def completion_of(raw: str, prompt: str) -> str:
    """The model's own completion. Agent prompts end with the JSON prefill, so the completion is
    whatever follows it; strip the prefill if the raw text carries it."""
    raw = raw or ""
    if prompt.endswith(AGENT_PREFILL) and raw.startswith(AGENT_PREFILL):
        return raw[len(AGENT_PREFILL):]
    return raw


def canonical(parsed: dict | None, prompt: str) -> str | None:
    """Policy's corrected output, serialized in the order the model was fine-tuned to emit."""
    if not parsed:
        return None
    if prompt.endswith(AGENT_PREFILL):
        ordered = {k: parsed[k] for k in FIELD_ORDER if k in parsed}
        return completion_of(json.dumps(ordered, ensure_ascii=False), prompt)
    # requires_human_approval is set structurally by policy (checkReport) and the model is never
    # asked to produce it. Leaving it in "chosen" would teach the model to emit a field it should not.
    return json.dumps({k: v for k, v in parsed.items() if k not in POLICY_ONLY_FIELDS}, ensure_ascii=False)


def calls_of(inc: dict):
    for a in inc.get("agents") or []:
        if a.get("prompt"):  # context agents are deterministic and carry no prompt
            yield "agent", a
    f = inc.get("final")
    if f and f.get("prompt") and not str(f.get("model", "")).startswith("deterministic"):
        yield "report", f


def export(lines: list[str], out: Path) -> Counter:
    out.mkdir(parents=True, exist_ok=True)
    stats = Counter()
    sft, dpo, dis = [], [], []
    for inc in latest_per_incident(lines):
        verdict = inc.get("approval", "pending")
        stats[f"incidents_{verdict}"] += 1
        for kind, c in calls_of(inc):
            prompt = c["prompt"]
            raw = completion_of(c.get("raw", ""), prompt)
            base = {"incident": inc["id"], "kind": kind, "role": c.get("role", "synthesizer"),
                    "model": c.get("model"), "verdict": verdict}
            if c.get("repairs") and c.get("parsed"):
                chosen = canonical(c["parsed"], prompt)
                if chosen and chosen.strip() != raw.strip():
                    dpo.append({**base, "prompt": prompt, "chosen": chosen, "rejected": raw,
                                "why": c["repairs"]})
                    stats["dpo_pairs"] += 1
            elif verdict == "approved" and c.get("valid") and not c.get("errors"):
                sft.append({**base, "prompt": prompt, "completion": raw})
                stats["sft_positive"] += 1
            if verdict == "dismissed":
                dis.append({**base, "prompt": prompt, "output": raw,
                            "note": inc.get("approval_note", ""), "errors": c.get("errors")})
                stats["dismissed_calls"] += 1

    for name, rows in (("sft_positive", sft), ("dpo_pairs", dpo), ("dismissed", dis)):
        with open(out / f"{name}.jsonl", "w", encoding="utf-8") as fh:
            for r in rows:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    return stats


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--log", help="local incidents.jsonl (default: pull from the QIDK)")
    ap.add_argument("--out", default=str(HERE / "data"))
    a = ap.parse_args()
    lines = Path(a.log).read_text(encoding="utf-8").splitlines() if a.log else pull_log()
    s = export(lines, Path(a.out))
    print(f"read {len(lines)} log lines -> {a.out}")
    for k in sorted(s):
        print(f"  {k}: {s[k]}")
