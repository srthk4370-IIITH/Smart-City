"""Spot-check ~55 numbers in Website/data/ against their sources. Exit 1 on any mismatch.

  py -3 Website/build/verify.py

Two kinds of check:
  * recompute: re-read the source file (JSON/JSONL/log) and recompute the value independently;
  * text: the published number must appear in the cited source text (HANDBOOK/RESULTS) near its keyword.
"""
