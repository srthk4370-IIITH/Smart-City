RESULTS = []


def ds(id):
    """A published dataset, or a removed one through the 'folded' entry of the dataset that absorbed it."""
    for t in TOPICS:
        p = DATA / t / f"{id}.json"
        if p.exists():
            return read_json(p)
    tgt = canon(id)
    for t in TOPICS:
        p = DATA / t / f"{tgt}.json"
        if p.exists():
            for f in read_json(p).get("folded", []):
                if f["id"] == id:
                    return {"meta": {"n": f["n"], "title": f["title"]}, "series": f["series"], **{k: f[k] for k in f if k in ("table", "paired_tests", "paired")}}
    raise KeyError(id)


def y(id, series, x, field="y"):
    d = ds(id)
    for s in d["series"]:
        if s["name"] == series:
            for p in s["points"]:
                if str(p["x"]) == str(x):
                    return p.get(field)
            # training evals can land a step off the nominal one after a resume (e.g. 2701 for 2700)
            if str(x).isdigit():
                near = [p for p in s["points"] if isinstance(p["x"], (int, float)) and abs(p["x"] - int(x)) <= 2]
                if near:
                    return near[0].get(field)
    raise KeyError((id, series, x))


def check(name, got, want, tol=0.0015):
    ok = (abs(float(got) - float(want)) <= tol) if isinstance(want, (int, float)) and got is not None else got == want
    RESULTS.append((ok, name, got, want))


def text_has(name, src, needle, value):
    t = text(src)
    ok = needle in t and str(value) in t
    RESULTS.append((ok, name, value, f"'{needle}' and '{value}' in {Path(src).name}"))


