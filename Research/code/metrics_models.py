"""metrics_models.py (item 7b): METRICS_MODELS.md (+ short HANDBOOK.md section) from results/textmetrics.json, metrics_gen/r4/*, agent text run. Run after the GPU chain (WSL venv rsn)."""
import json, os, re, subprocess, numpy as np
import sacrebleu
from rouge_score import rouge_scorer
Q = "/mnt/c/Users/hp/Desktop/qidk"; P = Q + "/proofs/2026-11-26_paper"; G = P + "/metrics_gen"
rs = rouge_scorer.RougeScorer(["rougeL"])
tm = json.load(open(P + "/results/textmetrics.json"))


def jp(t):
    try: return json.loads(t)
    except Exception:
        m = re.search(r"\{.*\}", t or "", re.S)
        try: return json.loads(m.group(0)) if m else None
        except Exception: return None


def sc(h, g):
    if not g: return None
    return dict(n=len(g), bleu=round(sacrebleu.corpus_bleu(h, [g]).score, 1), chrf=round(sacrebleu.corpus_chrf(h, [g]).score, 1), rougeL=round(100 * float(np.mean([rs.score(b, a)["rougeL"].fmeasure for a, b in zip(g, h)])), 1))


L = ["# METRICS_MODELS: BLEU / ROUGE-L / chrF and per-reasoning-type accuracy of every current model", "",
     "Generated by metrics_models.py (2026-11-26). Held-out free-text gold only; Q4_0 GGUFs on the host laptop GPU, greedy, think adaptive, same protocol as the frozen gates. BLEU = sacrebleu corpus BLEU, chrF = sacrebleu corpus chrF, ROUGE-L = mean F (rouge_score, no stemming); all x100. Caveat: part of every gold text is self-distilled (RESEARCH_PAPER.md section 7), so these are similarity-to-reference scores, not correctness; with n = 20-70 rows per slice differences of a few points are noise (CIs in results/textmetrics.json).", "",
     "Models: **p2** (rsn_v3_4b_p2_q4_0, previous board model), **r3c1** (rsn_v3_4b_r3c1_q4_0, oldest), **fix60** (rsn_v3_4b_full_q4_0_prev_1795632761), **v5 = rep50** (rsn_v3_4b_v5_q4_0, deployed; md5-identical to rsn_v3_4b_full_q4_0). rsn_v3_4b_full_q4_0 is the same file as v5 so it is not listed twice. Other reasoner checkpoints named in older notes (r3_s2000, r3_s2800, 2b, v1, v2) have no GGUF left in Code/models_stage and are not re-scored. Ceiling model: skipped (owner to decide).", ""]
L += ["## A. Frozen gate set, held-out free text (proofs/2026-11-21_rsn_full/gate_full/gate_set.jsonl)", "",
      "Report slice = 70 rows (report_all 40 + new_family 30), reference = gold JSON fields; chat_en = 40 rows and tool_chain = 20 rows, reference = gold final assistant answer.", "",
      "| model | report joined (root_cause+chain+explanation) BLEU / ROUGE-L / chrF | root_cause BLEU / R-L / chrF | explanation BLEU / R-L / chrF | valid JSON | chat_en BLEU / R-L / chrF | tool_chain BLEU / R-L / chrF |", "|---|---|---|---|---|---|---|"]
f3 = lambda s: "%.1f / %.1f / %.1f" % (s["bleu"], s["rougeL"], s["chrf"]) if s else "not run"
for m, o in tm.items():
    r = o.get("report") or {}
    L.append("| %s | %s | %s | %s | %s | %s | %s |" % (m, f3(r.get("joined")), f3(r.get("root_cause")), f3(r.get("explanation")), r.get("valid_json", "-"), f3(o.get("chat_en")), f3(o.get("tool_chain"))))
# ---------------------------------------------------------------- r4
L += ["", "## B. Held-out cross-domain test (proofs/2026-11-12_topup_r4 test_inc_r4), per reasoning type", "",
      "Stratified subset: 8 of the 720 held-out incidents per type (64 rows, seed 2611; metrics_gen/r4_subset.jsonl). Prompt = the app's older v3 incident prompt via run_r4_inc.py (think adaptive), scored with score_r4.py (severity / label vs gold; root-domain = domain of the first sensor in the causal chain). n = 8 per cell, so one row = 12.5 points. The v5 / fix60 / p2 models were trained on the newer incident_v4 format, so this old-format test understates them; r3c1 is closest to the test's format. Multihop items are all 3 hops (the test has no other hop count); chat reasoning items (test_chat_r4) were not run: their tool store (build/store_r4) is not on disk.", ""]
types = ["pair_relation", "pair_who", "pairwise", "transitive", "three_way", "multihop", "chain_direct", "chain_max"]
tags = ["p2", "fix60", "v5", "r3c1"]
summ = {}
gold = {json.loads(l)["id"]: json.loads(l) for l in open(G + "/r4_subset.jsonl", encoding="utf-8")}
for t in tags:
    out = "%s/r4/%s.jsonl" % (G, t)
    if not os.path.exists(out): continue
    js = "%s/r4/%s_summary.json" % (G, t)
    subprocess.run(["python3", Q + "/proofs/2026-11-12_topup_r4/tools/score_r4.py", "inc", "--out", out, "--rows", G + "/r4_subset.jsonl", "--json", js], capture_output=True)
    if os.path.exists(js): summ[t] = json.load(open(js))
if summ:
    for met, nm in (("severity", "severity acc"), ("label", "label acc"), ("root_domain_ok", "root-domain ok")):
        L += ["", "**%s** (n = 8 per type)" % nm, "", "| type | " + " | ".join(t for t in tags if t in summ) + " |", "|---|" + "---|" * len(summ)]
        for ty in types + ["all"]:
            cells = []
            for t in tags:
                if t not in summ: continue
                d = summ[t]["all"] if ty == "all" else summ[t].get("by_reasoning_type", {}).get(ty, {})
                v = d.get(met)
                cells.append("%.2f" % v if isinstance(v, (int, float)) else "-")
            L.append("| %s | %s |" % (ty, " | ".join(cells)))
    # text metrics on gold_text
    L += ["", "**Free-text similarity on the r4 subset** (generated title+root_cause+causal_chain+explanation vs gold_text; BLEU / ROUGE-L / chrF)", "", "| type | " + " | ".join(t for t in tags if t in summ) + " |", "|---|" + "---|" * len(summ)]
    H = {}
    for t in tags:
        if t not in summ: continue
        for l in open("%s/r4/%s.jsonl" % (G, t)):
            o = json.loads(l); g = gold.get(o["id"])
            if not g: continue
            h = jp(o.get("json_text") or "") or {}
            ref = g.get("gold_text") or {}
            if isinstance(ref, str): ref = jp(ref) or {}
            j = lambda d: " ".join(str(d.get(k) or "") for k in ("title", "root_cause", "causal_chain", "explanation"))
            H.setdefault((t, g["reasoning_type"]), ([], []))
            H[(t, g["reasoning_type"])][0].append(j(h)); H[(t, g["reasoning_type"])][1].append(j(ref))
    for ty in types + ["all"]:
        cells = []
        for t in tags:
            if t not in summ: continue
            if ty == "all":
                hh = [x for k, v in H.items() if k[0] == t for x in v[0]]; gg = [x for k, v in H.items() if k[0] == t for x in v[1]]
            else:
                hh, gg = H.get((t, ty), ([], []))
            s = sc(hh, gg); cells.append(f3(s) if s else "-")
        L.append("| %s | %s |" % (ty, " | ".join(cells)))
else:
    L.append("(r4 runs not finished)")
# ---------------------------------------------------------------- agent
L += ["", "## C. Domain agent GGUF (agt3_s0450_q4_0, deployed NPU agent)", ""]
ao = G + "/agent_text_out.jsonl"
if os.path.exists(ao):
    gold_a = {json.loads(l)["id"]: json.loads(l) for l in open(G + "/agent_text_gold.jsonl")}
    hs, gs, hs2, gs2 = [], [], [], []
    valid = 0; n = 0
    for l in open(ao):
        o = json.loads(l); g = gold_a.get(o["id"]);
        if not g: continue
        n += 1
        c = jp(g["completion"].replace("<|eot_id|>", "")) or {}
        h = jp(o.get("text") or "")
        if h is None:
            t = o.get("text") or ""
            h = jp(t + ': "none"}') or {}
        else: valid += 1
        hs.append(str(h.get("severity_reason") or "")); gs.append(str(c.get("severity_reason") or ""))
        hs2.append(" ".join(h.get("observations") or [])); gs2.append(" ".join(c.get("observations") or []))
    L += ["160 random held-out rows from agt_v3 test_campus + test_unseen_layout (metrics_gen/agent_text_gold.jsonl), app prompt + JSON prefill, greedy; reference = gold completion. The output is cut at \"action\" as in the app, so an action value is appended before parsing (strictly valid as-is: %d of %d)." % (valid, n), "",
          "| field | n | BLEU / ROUGE-L / chrF |", "|---|---|---|", "| severity_reason | %d | %s |" % (n, f3(sc(hs, gs))), "| observations (joined) | %d | %s |" % (n, f3(sc(hs2, gs2))), ""]
else:
    L += ["Agent run did not finish.", ""]
L += ["Per-row raw outputs: metrics_gen/res/ (gate set), metrics_gen/r4/, metrics_gen/agent_text_out.jsonl; scripts textmetrics.py, metrics_models.py, metrics_gen/*.sh.", ""]
open(P + "/METRICS_MODELS.md", "w", newline="\n").write("\n".join(L))
hb = open(Q + "/HANDBOOK.md", encoding="utf-8").read()
if "METRICS_MODELS" not in hb:
    j = tm.get("v5 = rep50 (full_q4_0, deployed)", {}).get("report", {}).get("joined")
    open(Q + "/HANDBOOK.md", "a", newline="\n", encoding="utf-8").write("\n\n## Text metrics and per-reasoning-type accuracy of every current model (2026-11-26)\n\nBLEU / ROUGE-L / chrF for p2, r3c1, fix60 and v5 (deployed) on the frozen gate set, per-reasoning-type accuracy on a stratified slice of the held-out r4 cross-domain test, and the domain agent's text scores: proofs/2026-11-26_paper/METRICS_MODELS.md (scripts textmetrics.py, metrics_models.py). v5 report text on the gate set: %s (BLEU / ROUGE-L / chrF). Ceiling model skipped (owner decides).\n" % (f3(j)))
